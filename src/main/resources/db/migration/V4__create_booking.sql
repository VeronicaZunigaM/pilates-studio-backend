CREATE TABLE booking (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT       NOT NULL REFERENCES users (id),
    lesson_id       BIGINT       NOT NULL REFERENCES lesson (id),
    subscription_id BIGINT       NOT NULL REFERENCES subscription (id),
    status          VARCHAR(255) NOT NULL,
    created_at      TIMESTAMP    NOT NULL,
    cancelled_at    TIMESTAMP,
    CHECK (status IN ('CONFIRMED', 'CANCELLED', 'LATE_CANCELLED'))
);

CREATE INDEX idx_booking_user   ON booking (user_id);
CREATE INDEX idx_booking_lesson ON booking (lesson_id);

-- Una cliente non può avere due prenotazioni ATTIVE per la stessa lezione
CREATE UNIQUE INDEX uq_booking_active
    ON booking (user_id, lesson_id)
    WHERE status = 'CONFIRMED';